#!/usr/bin/env bash
# 02-everything-is-a-file.sh — /proc, /dev, /sys are alive, not on disk.
# Run: ./02-everything-is-a-file.sh
set -u
say() { printf '\n=== %s ===\n' "$*"; }

say "1. Your shell, as the kernel sees it (/proc/$$)"
head -4 "/proc/$$/status"
echo "--- cmdline (NUL-separated, exactly as execve received it):"
tr '\0' ' ' < "/proc/$$/cmdline"; echo

say "2. Your shell's open files (its fd table, rendered as symlinks)"
ls -l "/proc/$$/fd"

say "3. Devices are files too"
echo "hello" > /dev/null && echo "wrote to /dev/null: bytes accepted, discarded by driver"
head -c 16 /dev/urandom | od -An -tx1 | head -1
echo "(above: 16 random bytes generated by the kernel CSPRNG at read time)"

say "4. Hardware/kernel attributes are files (/sys)"
for f in /sys/class/net/lo/operstate /sys/devices/system/cpu/online; do
  [ -r "$f" ] && echo "$f = $(cat "$f")"
done

say "5. Nothing above lives on disk — the kernel generates it per-read"
stat -c '%n: size=%s blocks=%b' "/proc/$$/status" /dev/null
echo "(0 blocks = no disk storage; content is generated when you read)"
